const API_BASE = "http://localhost:5000/api";

const token = localStorage.getItem("carbontrace_token");

const user = JSON.parse(
    localStorage.getItem("carbontrace_user") || "{}"
);

const currentPage = window.location.pathname.split("/").pop();

// Check authentication
if (!token) {
    window.location.href = "login.html";
}

// Escape displayed text
function escapeHTML(value) {
    return String(value ?? "").replace(/[&<>"']/g, function (character) {
        return {
            "&": "&amp;",
            "<": "&lt;",
            ">": "&gt;",
            '"': "&quot;",
            "'": "&#39;"
        }[character];
    });
}

// API request
async function apiRequest(endpoint) {
    const response = await fetch(`${API_BASE}${endpoint}`, {
        headers: {
            Authorization: `Bearer ${token}`
        }
    });

    const result = await response.json();

    if (!response.ok) {
        throw new Error(result.message || "Unable to load data");
    }

    return result;
}

// Logout
const logoutButton = document.getElementById("logoutBtn");

if (logoutButton) {
    logoutButton.addEventListener("click", function () {
        localStorage.removeItem("carbontrace_token");
        localStorage.removeItem("carbontrace_user");
        window.location.href = "login.html";
    });
}

// Supplier dashboard
async function loadSupplierDashboard() {
    const message = document.getElementById("dashboardMessage");

    try {
        const activities = await apiRequest("/activities/mine");

        // Total estimated emissions
        const total = activities.reduce(
            (sum, activity) =>
                sum + Number(activity.emissionsKgCO2e || 0),
            0
        );

        document.getElementById("totalEmissions").textContent =
            total.toFixed(2);

        // Activity count
        document.getElementById("activityCount").textContent =
            activities.length;

        // Category totals
        const categoryTotals = {};

        activities.forEach(activity => {
            const category = activity.category;

            categoryTotals[category] =
                (categoryTotals[category] || 0) +
                Number(activity.emissionsKgCO2e || 0);
        });

        const sortedCategories = Object.entries(categoryTotals)
            .sort((a, b) => b[1] - a[1]);

        document.getElementById("topCategory").textContent =
            sortedCategories.length > 0
                ? sortedCategories[0][0]
                : "—";

        // Emission bars
        const breakdown = document.getElementById("breakdown");

        if (sortedCategories.length === 0) {
            breakdown.innerHTML =
                "<p>No activities available. Add your first activity.</p>";
        } else {
            const maximum = Math.max(
                1,
                ...sortedCategories.map(item => item[1])
            );

            breakdown.innerHTML = sortedCategories.map(
                ([category, value]) => {
                    const percentage = (value / maximum) * 100;

                    return `
                        <div class="bar-row">
                            <span>${escapeHTML(category)}</span>

                            <div class="bar-track">
                                <div class="bar-fill"
                                     style="width:${percentage}%">
                                </div>
                            </div>

                            <strong>${value.toFixed(2)}</strong>
                        </div>
                    `;
                }
            ).join("");
        }

        // Simple rule-based suggestions for the dashboard.
        // These are not generated by the Python AI engine.
        const recommendations =
            document.getElementById("recommendations");

        if (sortedCategories.length === 0) {
            recommendations.innerHTML =
                "<p>Add activities to see suggested sustainability actions.</p>";
        } else {
            const ideas = {
                electricity:
                    "Review electricity usage and consider verified renewable energy options.",
                fuel:
                    "Review fuel consumption, vehicle maintenance and avoidable idling.",
                transport:
                    "Explore route planning and shipment consolidation.",
                waste:
                    "Measure waste streams and improve reduction, reuse and recycling."
            };

            recommendations.innerHTML = sortedCategories.map(
                ([category]) => `
                    <div class="activity-item">
                        <span>${escapeHTML(category)}</span>
                        <span>${ideas[category] || "Review this activity and collect more data."}</span>
                    </div>
                `
            ).join("");
        }

        // Anomaly detection placeholder
        document.getElementById("anomalyResults").innerHTML =
            "<p>Python anomaly detection is a separate demo module and has not yet been connected to this dashboard.</p>";

        // Show admin link only for an admin account
        if (user.role === "admin") {
            const adminLink = document.getElementById("adminLink");

            if (adminLink) {
                adminLink.classList.remove("hidden");
            }
        }

    } catch (error) {
        message.textContent = error.message;
    }
}

// Admin dashboard
async function loadAdminDashboard() {
    const message = document.getElementById("adminMessage");

    if (user.role !== "admin") {
        message.textContent = "Admin access required.";
        return;
    }

    try {
        const [suppliers, activities] = await Promise.all([
            apiRequest("/suppliers"),
            apiRequest("/activities/all")
        ]);

        // Supplier table
        const supplierTable = document.getElementById("supplierTable");

        if (suppliers.length === 0) {
            supplierTable.innerHTML = "<p>No suppliers registered.</p>";
        } else {
            supplierTable.innerHTML = `
                <div class="table-wrapper">
                <table>
                    <thead>
                        <tr>
                            <th>Company</th>
                            <th>Email</th>
                            <th>Industry</th>
                        </tr>
                    </thead>
                    <tbody>
                        ${suppliers.map(supplier => `
                            <tr>
                                <td>${escapeHTML(supplier.companyName)}</td>
                                <td>${escapeHTML(supplier.user?.email || "—")}</td>
                                <td>${escapeHTML(supplier.industry || "—")}</td>
                            </tr>
                        `).join("")}
                    </tbody>
                </table>
                </div>
            `;
        }

        // Activity table
        const adminActivities =
            document.getElementById("adminActivities");

        if (activities.length === 0) {
            adminActivities.innerHTML = "<p>No activities submitted.</p>";
        } else {
            adminActivities.innerHTML = `
                <div class="table-wrapper">
                <table>
                    <thead>
                        <tr>
                            <th>Supplier</th>
                            <th>Category</th>
                            <th>Quantity</th>
                            <th>Estimated CO₂e</th>
                        </tr>
                    </thead>
                    <tbody>
                        ${activities.map(activity => `
                            <tr>
                                <td>${escapeHTML(activity.supplier?.companyName || "—")}</td>
                                <td>${escapeHTML(activity.category)}</td>
                                <td>${activity.quantity} ${escapeHTML(activity.unit)}</td>
                                <td>${Number(activity.emissionsKgCO2e).toFixed(2)} kg</td>
                            </tr>
                        `).join("")}
                    </tbody>
                </table>
                </div>
            `;
        }

    } catch (error) {
        message.textContent = error.message;
    }
}

// Select the correct page
if (currentPage === "admin.html") {
    loadAdminDashboard();
} else if (currentPage === "dashboard.html") {
    loadSupplierDashboard();
}